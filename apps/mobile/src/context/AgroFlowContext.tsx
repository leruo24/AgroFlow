// A sensor with no reading in the last hour reads as Offline - the
// firmware reports roughly every 30s while connected (see
// hardware/shared/MQTT_TOPICS.md), so an hour of silence is a real signal,
// not just "hasn't reported yet this second".
const SENSOR_STALE_AFTER_MS = 60 * 60 * 1000;

function deriveSensorStatus(
  lastReadingAt: string | null
): SensorStatus {
  if (!lastReadingAt) return 'Offline';
  const ageMs = Date.now() - new Date(lastReadingAt).getTime();
  return ageMs <= SENSOR_STALE_AFTER_MS ? 'Online' : 'Offline';
}

// No reading yet defaults to 'Optimal' (neutral, not alarming) rather than
// 'Dry' - the sensor's own Online/Offline status above is the honest
// signal that there's no data; this just avoids implying a problem that
// isn't known to exist.
function deriveMoistureStatus(
  moisture: number | null,
  dryThreshold: number,
  wetThreshold: number
): MoistureStatus {
  if (moisture === null) return 'Unknown';
  if (moisture < dryThreshold) return 'Dry';
  if (moisture > wetThreshold) return 'Wet';
  return 'Optimal';
}

function mapZoneRow(
  row: ZoneRow,
  index: number,
  reading: ZoneLatestReadingRow | undefined,
  lastEvent: IrrigationEventRow | undefined,
  usedTodayLitres: number | null,
  weather: WeatherRow | null,
  zoneAlerts: AlertRow[]
): Zone {
  const moistureThreshold =
    Number(row.moisture_threshold ?? 30);
  const desiredMoisture =
    Number(row.desired_moisture ?? 60);

  const rawMoisture =
    reading?.moisture != null
      ? Number(reading.moisture)
      : null;
  // Item 2: a percentage only after the wet/dry setup; before it, the
  // sensor's own number, with no Dry/Wet verdict drawn from it.
  const calibrationWet =
    row.calibration_wet != null ? Number(row.calibration_wet) : null;
  const calibrationDry =
    row.calibration_dry != null ? Number(row.calibration_dry) : null;
  const relativeMoisture =
    relativeMoisturePercent(rawMoisture, calibrationWet, calibrationDry);
  const calibrated = relativeMoisture != null;
  const moistureValue =
    calibrated
      ? Math.round(relativeMoisture * 10) / 10
      : rawMoisture;
  const temperatureValue =
    reading?.temperature != null
      ? Number(reading.temperature)
      : null;
  const humidityValue =
    reading?.humidity != null
      ? Number(reading.humidity)
      : null;
  const sensorStatus =
    deriveSensorStatus(reading?.last_reading_at ?? null);

  const runtimeSeconds =
    lastEvent?.runtime_seconds != null
      ? Number(lastEvent.runtime_seconds)
      : 0;
  const estimatedLitres =
    lastEvent?.estimated_litres != null
      ? Number(lastEvent.estimated_litres)
      : 0;
  const [lastIrrigationDate, lastIrrigationTime] =
    lastEvent
      ? lastEvent.started_at.split('T')
      : ['Never', ''];

  const weatherConditions =
    weather?.weather_conditions?.trim() ?? '';
  const rainExpected =
    weatherConditions.toLowerCase().includes('rain');
  const weatherMessage =
    weather
      ? weatherConditions || 'No conditions recorded'
      : 'No weather data available';

  return {
    id:
      String(
        row.id
      ),
    farmId:
      String(
        row.farm_id
      ),
    name:
      row.name?.trim() ||
      'Unnamed zone',
    location:
      row.location?.trim() ||
      'Not configured',
    crop:
      row.crop_type?.trim() ||
      'Not configured',
    plantingDate:
      row.planting_date ??
      null,
    healthStatus:
      row.health_status ??
      'Unknown',
    waterSavedLitres:
      row.water_saved == null
        ? null
        : Number(row.water_saved),
    size: {
      value:
        Number(
          row.size_value ?? 0
        ),
      unit:
        row.size_unit ?? 'ha',
    },
    sensors: {
      soilMoisture: {
        value: moistureValue ?? 0,
        unit: calibrated ? '%' : '',
        status: moistureValue == null ? 'Offline' : sensorStatus,
        moistureStatus: deriveMoistureStatus(
          calibrated ? moistureValue : null, moistureThreshold, desiredMoisture
        ),
        calibrated,
      },
      temperatureHumidity: {
        temperature: temperatureValue ?? 0,
        temperatureUnit: '°C',
        humidity: humidityValue ?? 0,
        humidityUnit: '%',
        status: temperatureValue == null || humidityValue == null ? 'Offline' : sensorStatus,
      },
    },
    irrigation: {
      status:
        row.irrigation_mode ===
        'scheduled'
          ? 'Scheduled'
          : 'Off',
      mode:
        row.irrigation_mode ===
        'scheduled'
          ? 'scheduled'
          : 'automatic',
      lastIrrigation: {
        date: lastIrrigationDate,
        time: lastIrrigationTime.slice(0, 5),
        durationMinutes: Math.round(runtimeSeconds / 60),
      },
      schedule: {
        enabled:
          row.schedule_enabled === true,
        days:
          Array.isArray(row.schedule_days)
            ? row.schedule_days
            : [],
        startTime:
          row.schedule_start_time
            ?.trim()
            .slice(0, 5) ?? '',
        durationMinutes:
          Number(
            row.schedule_duration_minutes ?? 0
          ),
      },
      automation: {
        enabled:
          row.irrigation_mode !==
          'scheduled',
        moistureThreshold,
        desiredMoisture,
        weatherAdjustment:
          row.weather_adjustment ??
          true,
      },
      override: {
        active:
          false,
        durationMinutes:
          null,
      },
    },
    // relay/pump: no reliable "is it actively running right now" signal
    // exists in the schema - hardware.status only distinguishes
    // Online/Offline connectivity, not an actuation state. Defaulting to
    // Off rather than inventing one; see the Phase 6 summary.
    relay: {
      status: 'Unknown',
    },
    pump: {
      status: 'Unknown',
    },
    water: {
      usedTodayLitres,
      latestCycleLitres: estimatedLitres,
      flowRateLpm:
        runtimeSeconds > 0
          ? Math.round((estimatedLitres / (runtimeSeconds / 60)) * 10) / 10
          : 0,
    },
    weather: {
      rainExpected,
      message: weatherMessage,
    },
    alerts: zoneAlerts.map((a) => ({
      id: String(a.id),
      type: a.severity,
      message: a.message,
    })),
  };
}

async function fetchZonesForFarm(
  farmId: string
): Promise<{ zones: Zone[]; alerts: AlertEntry[]; history: HistoryEntry[] }> {
  const dashboard =
    await fetchFarmerDashboard(farmId);
  const rows = dashboard.zones
    .filter((row) => String(row.farm_id) === farmId) as ZoneRow[];
  const readings = dashboard.readings as ZoneLatestReadingRow[];
  const events = dashboard.events as IrrigationEventRow[];
  const usage = dashboard.usage as WaterUsageRow[];
  const weatherRows = dashboard.weather as WeatherRow[];
  const alertRows = (dashboard.alerts as (AlertRow & { status?: string })[])
    .filter((alert) => !alert.status || alert.status === 'Open');

  const readingByZone = new Map<string, ZoneLatestReadingRow>(
    ((readings ?? []) as ZoneLatestReadingRow[]).map((r) => [String(r.zone_id), r])
  );
  // events are ordered newest-first, so the first one seen per zone is its
  // latest - a single pass keeps only that one.
  const latestEventByZone = new Map<string, IrrigationEventRow>();
  for (const event of (events ?? []) as IrrigationEventRow[]) {
    const key = String(event.zone_id);
    if (!latestEventByZone.has(key)) latestEventByZone.set(key, event);
  }
  const usageByZone = new Map<string, number>(
    ((usage ?? []) as WaterUsageRow[]).map((u) => [
      String(u.zone_id), Number(u.used_today_litres ?? 0),
    ])
  );
  const latestWeather = ((weatherRows ?? []) as WeatherRow[])[0] ?? null;
  const alertsByZone = new Map<string, AlertRow[]>();
  for (const alert of (alertRows ?? []) as AlertRow[]) {
    if (alert.zone_id === null) continue;
    const key = String(alert.zone_id);
    const list = alertsByZone.get(key) ?? [];
    list.push(alert);
    alertsByZone.set(key, list);
  }

  const mappedZones = rows.map((row, index) =>
    mapZoneRow(
      row,
      index,
      readingByZone.get(String(row.id)),
      latestEventByZone.get(String(row.id)),
      // undefined (no zone_daily_water_usage row for today) stays null -
      // never collapsed to 0, which would be indistinguishable from a real
      // recorded zero.
      usageByZone.get(String(row.id)) ?? null,
      latestWeather,
      alertsByZone.get(String(row.id)) ?? []
    ));

  const zoneNames = new Map(
    rows.map((row) => [String(row.id), row.name ?? `Zone ${row.id}`])
  );
  const mappedAlerts: AlertEntry[] = alertRows
    .filter((alert) => alert.zone_id !== null)
    .map((alert) => ({
      id: `database-${alert.id}`,
      farmId,
      type: alert.severity.toLowerCase(),
      title: `${alert.severity} Alert`,
      message: alert.message,
      zone: zoneNames.get(String(alert.zone_id)) ?? null,
      zoneId: String(alert.zone_id),
      timestamp: alert.created_at ?? '',
      read: false,
    }));

  return {
    zones: mappedZones,
    alerts: mappedAlerts,
    history: events.map((event, index) => ({
      id: `database-event-${farmId}-${index}-${event.started_at}`,
      farmId,
      ...describeEvent(event),
      zone: zoneNames.get(String(event.zone_id)) ?? 'Zone',
      timestamp: event.started_at,
      type: 'irrigation',
    })),
  };
}

