export type PublicLanguage = "en" | "af" | "tn";
export type CopyKey = keyof typeof copy;
export function publicLanguage(): PublicLanguage {
  try {
    const value = localStorage.getItem("agroflow_public_language");
    return value === "af" || value === "tn" ? value : "en";
  } catch {
    return "en";
  }
}
export function text(key: CopyKey): string {
  return (
    copy[key][["en", "af", "tn"].indexOf(publicLanguage())] ?? copy[key][0]
  );
}
